"""Command line: `pyjs FILE`, `pyjs build PATH...`, `pyjs show FILE`."""
import argparse
import importlib.util
import os
import sys
import traceback

from .runner import run_file
from .transpiler import PyJSSyntaxError, transpile

HELP = """usage:
  pyjs FILE [ARGS...]           run a .pyjs file (same as: pyjs run FILE)
  pyjs build PATH... [-o OUT]   write transpiled .py files next to the sources
  pyjs show FILE                print the generated Python
"""


def _read(path):
    with open(path, "rb") as handle:
        return importlib.util.decode_source(handle.read())


def _run(args):
    if not args:
        sys.stdout.write(HELP)
        return 2
    path, rest = args[0], args[1:]
    if not os.path.isfile(path):
        sys.stderr.write("pyjs: can't open file {!r}\n".format(path))
        return 2
    run_file(path, rest)
    return 0


def _show(args):
    parser = argparse.ArgumentParser(prog="pyjs show")
    parser.add_argument("file")
    options = parser.parse_args(args)
    sys.stdout.write(transpile(_read(options.file), options.file))
    return 0


def _collect(paths):
    files = []
    for path in paths:
        if os.path.isdir(path):
            for root, _dirs, names in os.walk(path):
                files += [os.path.join(root, n) for n in sorted(names) if n.endswith(".pyjs")]
        elif os.path.isfile(path):
            files.append(path)
        else:
            raise FileNotFoundError(path)
    return files


def _build(args):
    parser = argparse.ArgumentParser(prog="pyjs build")
    parser.add_argument("paths", nargs="+", help=".pyjs files or folders")
    parser.add_argument("-o", "--output", help="output file (single input only)")
    options = parser.parse_args(args)

    try:
        files = _collect(options.paths)
    except FileNotFoundError as error:
        sys.stderr.write("pyjs: no such file or folder: {}\n".format(error))
        return 2
    if options.output and len(files) != 1:
        sys.stderr.write("pyjs: -o needs exactly one input file\n")
        return 2

    for path in files:
        result = transpile(_read(path), path)
        if not result.endswith("\n"):
            result += "\n"
        # Footer, not header, so line numbers still match the source.
        result += "# Generated by pyjs from {} -- do not edit.\n".format(os.path.basename(path))
        target = options.output or (
            path[: -len(".pyjs")] + ".py" if path.endswith(".pyjs") else path + ".py"
        )
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(result)
        print("built {} -> {}".format(path, target))
    return 0


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in ("-h", "--help", "help"):
        sys.stdout.write(HELP)
        return 0 if argv else 2
    handlers = {"build": _build, "show": _show, "run": _run}
    if argv[0] in handlers:
        handler, rest = handlers[argv[0]], argv[1:]
    else:
        handler, rest = _run, argv
    try:
        return handler(rest)
    except PyJSSyntaxError as error:
        sys.stderr.write("".join(traceback.format_exception_only(type(error), error)))
        return 1
